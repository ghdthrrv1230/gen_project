function renderComments(data) {
  const el=document.getElementById("main-comment-list"); if(!el)return;
  if(!data||typeof data!=="object"){
    el.innerHTML="<p class='comment-text' style='text-align:center;color:#94a3b8;padding:20px 0;'>첫 번째 방명록을 남겨보세요!</p>";
    return;
  }
  el.innerHTML=Object.values(data).filter(v=>v&&typeof v==="object")
    .sort((a,b)=>(b.createdAt||0)-(a.createdAt||0))
    .map(c=>`<div class="comment-item">
      <div class="comment-meta"><strong>${escapeHtml(c.name||"익명")}</strong><span>${formatDate(c.createdAt)}</span></div>
      <p class="comment-text">${escapeHtml(c.content||"").replace(/\n/g,"<br>")}</p>
    </div>`).join("");
}

window.addComment = function(prefix) {
  const nameEl=document.getElementById(`${prefix}-comment-name`);
  const contentEl=document.getElementById(`${prefix}-comment-input`);
  if(!nameEl||!contentEl)return;
  const name=nameEl.value.trim(),content=contentEl.value.trim();
  if(!name||!content){alert("이름과 내용을 모두 입력해주세요!");return;}
  if(name==="!관리자입장"&&content==="열려라참깨"){
    alert("관리자 권한이 확인되었습니다.");
    nameEl.value="";contentEl.value="";
    ["start-screen","quiz-screen","explanation-screen","result-screen",
     "knowledge-result-screen","tendency-screen","research-screen"]
      .forEach(id=>document.getElementById(id).classList.add("hidden"));
    document.getElementById("admin-screen").classList.remove("hidden");
    return;
  }
  push(ref(db,"comments"),{name,content,createdAt:Date.now()})
    .then(()=>{nameEl.value="";contentEl.value="";alert("방명록이 등록되었습니다!");})
    .catch(()=>alert("저장에 실패했습니다."));
};

