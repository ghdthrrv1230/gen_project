window.startKnowledgeQuiz = function() {
  // 카테고리별 최대 3개씩 랜덤 선택
  const byCategory={};
  KNOWLEDGE_QUIZZES.forEach(q=>{
    const cat=q.category||"기타";
    if(!byCategory[cat])byCategory[cat]=[];
    byCategory[cat].push(q);
  });
  const selected=[];
  Object.values(byCategory).forEach(group=>shuffle(group).slice(0,3).forEach(q=>selected.push(q)));
  currentMode="knowledge"; currentIdx=0; knowledgeScore=0; categoryStats={};
  currentList=shuffle(selected);
  hideAllScreens();
  document.getElementById("quiz-screen").classList.remove("hidden");
  window.scrollTo({top:0, behavior:"smooth"});
  renderQuestion();
};

function renderQuestion() {
  const q=currentList[currentIdx]; if(!q){goHome();return;}
  document.getElementById("total-idx").innerText=currentList.length;
  document.getElementById("current-idx").innerText=currentIdx+1;
  document.getElementById("progress-bar").style.width=`${((currentIdx+1)/currentList.length)*100}%`;
  document.getElementById("question-category").innerText=q.category||"";
  document.getElementById("question-text").innerText=q.question||"";
  const container=document.getElementById("options-container");
  container.innerHTML="";
  if(currentMode==="tendency"){
    shuffle(q.options||[]).forEach(opt=>{
      const btn=document.createElement("button");
      btn.innerText=opt.text||"";
      btn.onclick=()=>handleTendencyAnswer(opt.type||"A");
      container.appendChild(btn);
    });
  } else {
    shuffle(q.options||[]).forEach(opt=>{
      const btn=document.createElement("button");
      btn.innerText=opt||"";
      btn.onclick=()=>handleKnowledgeAnswer(opt,q);
      container.appendChild(btn);
    });
  }
}

function handleTendencyAnswer(type) {
  scores[type]=(scores[type]||0)+1; currentIdx++;
  currentIdx<currentList.length?renderQuestion():showTendencyResult();
}

function handleKnowledgeAnswer(selected,q) {
  document.getElementById("quiz-screen").classList.add("hidden");
  document.getElementById("explanation-screen").classList.remove("hidden");
  const isCorrect=selected===q.answer;
  const expTitle=document.getElementById("explanation-title");
  if(!categoryStats[q.category])categoryStats[q.category]=0;
  if(isCorrect){
    knowledgeScore++;categoryStats[q.category]++;
    expTitle.innerHTML=`<span class="material-symbols-rounded status-icon correct">check_circle</span> 정답입니다!`;
    expTitle.className="icon-header correct";
  } else {
    expTitle.innerHTML=`<span class="material-symbols-rounded status-icon incorrect">cancel</span> 아쉽네요. 오답입니다.`;
    expTitle.className="icon-header incorrect";
  }
  document.getElementById("explanation-desc").innerText=q.evidence||"";
  const expImg=document.getElementById("explanation-image");
  if(q.imageUrl){expImg.src=q.imageUrl;expImg.classList.remove("hidden");}
  else{expImg.src="";expImg.classList.add("hidden");}
  const tooltip=document.getElementById("source-tooltip");
  tooltip.innerHTML=(q.links&&q.links.length>0)
    ?q.links.map(l=>`<a href="${sanitizeUrl(l.url)}" target="_blank" rel="noopener noreferrer">${escapeHtml(l.title)}</a>`).join("")
    :`<span style="font-size:0.9rem;padding:6px 8px;">등록된 자료가 없습니다.</span>`;
}

