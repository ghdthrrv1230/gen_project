function buildResearchCard(item) {
  const tags=Array.isArray(item.tags)?item.tags.map(t=>`<span class="research-tag">${escapeHtml(t)}</span>`).join(""):"";
  const boxes=Array.isArray(item.boxes)&&item.boxes.length>0
    ?`<div class="research-boxes">${item.boxes.map(b=>`<div class="research-box"><div class="research-box-title">${escapeHtml(b.title)}</div><div class="research-box-desc">${escapeHtml(b.desc)}</div></div>`).join("")}</div>`:"";
  const stats=Array.isArray(item.stats)&&item.stats.length>0
    ?`<div class="research-stats">${item.stats.map(s=>`<div class="research-stat"><div class="research-stat-num">${escapeHtml(s.num)}</div><div class="research-stat-label">${escapeHtml(s.label)}</div></div>`).join("")}</div>`:"";
  const svg=typeof item.svg==="string"&&item.svg.trim().startsWith("<svg")?`<div class="research-svg">${item.svg}</div>`:"";
  const sources=Array.isArray(item.sources)&&item.sources.length>0
    ?`<div class="research-sources">${item.sources.map(s=>`<a class="research-source-link" href="${sanitizeUrl(s.url)}" target="_blank" rel="noopener noreferrer"><span class="material-symbols-rounded" style="font-size:0.9rem;">library_books</span>${escapeHtml(s.title)}</a>`).join("")}</div>`:"";
  return `<div class="research-card">
    <div class="research-card-title">${escapeHtml(item.title||"")}</div>
    ${tags?`<div class="research-card-tags">${tags}</div>`:""}
    <div class="research-card-desc">${escapeHtml(item.desc||"")}</div>
    ${boxes}${stats}${svg}${sources}
  </div>`;
}

